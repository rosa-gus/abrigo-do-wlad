import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { entries } from "./registry.mjs";

// Hash the original definition bytes, exactly as the CLI does, before bundling.
export function generateWorkerRegistry() {
  const imports = entries.map(([, file], index) =>
    `import migration${index} from ${JSON.stringify(`./definitions/${file.pathname.split("/").at(-1)}`)};`);
  const definitions = entries.map(([, file], index) => {
    const checksum = createHash("sha256").update(readFileSync(file)).digest("hex");
    return `  { ...migration${index}, checksum: ${JSON.stringify(checksum)} },`;
  });
  const source = `// Generated by generate-worker-registry.mjs; do not edit.\n${imports.join("\n")}\nexport const migrations = [\n${definitions.join("\n")}\n];\n`;
  const target = new URL("./worker-registry.mjs", import.meta.url);
  let previous;
  try { previous = readFileSync(target, "utf8"); } catch { /* First build. */ }
  if (previous !== source) writeFileSync(target, source);
}
